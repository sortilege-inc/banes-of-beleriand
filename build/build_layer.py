#!/usr/bin/env python3
"""
build_layer.py — an instance's own DSL layer (its homebrew: Player-heroes, Loremaster
characters, adversaries, an adventure of its own, lore) built as one more book, and gated as the
books are.

    python3 build/build_layer.py <layer dir> --id campaign --label "<the campaign's title>" --out campaign/data

An instance is a campaign repo forked from this VTT (PLAN.md, "Instances"); its layer lives in
its own folder and never in data/. This writes two files into --out:

  <id>.js    the layer's entities — a self-registering book file, loaded on demand like any book
  index.js   the layer's index record and its records, merged ahead of the corpus's at the `data`
             stage (engine/instance.js), so every list view leads with the layer

then gates them, and exits non-zero on any failure:

  1. COVERAGE and FIDELITY, by count — verify_data.py's rule over the layer's own files: every
     string the layer prints reaches its data as often as it is printed, and nothing in the
     data came from anywhere else.
  2. IDS — no entity of the layer takes an id the corpus uses.
  3. REFERENCES — every id the layer points at (the type a DEF EXTENDS, a LIST OF type, a
     reference, a CONCERNS entry, a SCENE_REF) is an entity or block of the layer or of the
     corpus. A homebrew adversary built on a mistyped type fails here, not at the table.
  4. NAMES — a reference with no hash (`^"Awe"` in a list of Skills) must name an entity of the
     layer or the corpus. A name that matches none fails; one that matches several is reported.

Records are listed by the BASE's declared types, read from data/index.js, so a layer's
Adversary or Loremaster Character appears in every list the corpus's do. The corpus side is
read from data/*.js, so the books must be built first (build/build.sh).
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_data import (DSL_EXTS, LORE_EXTS, KINDS, chapter_body, collect_entities,  # noqa: E402
                        first_page, kwstr, lore_chapter, reading_order, records_of)
from parse_dsl import parse_files  # noqa: E402
from verify_data import BLOB, INDEX_BLOB, TYPE_WORDS, data_strings, strings_of  # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIND = "campaign"
LAYER_BLOB = re.compile(r"var d=(\{.*\});var T=window\.TOR2E", re.S)
EXT_ORDER = {".ttrpg": 0, ".actor": 1, ".arc": 2, ".frame": 3, ".lore": 4}

BANNER = ("/* Generated by build/build_layer.py from this instance's DSL layer — do not edit by hand.\n"
          "   Every string is verbatim from the layer's files; regenerate rather than patch. */\n")
REGISTER = """(function(){var d=%s;var T=window.TOR2E=window.TOR2E||{books:{},entities:{},loaded:{}};
T.loaded[d.src]=true;T.books[d.book.id]=d.book;
for(var h in d.entities){T.entities[h]=d.entities[h];}})();
"""
# Merged into the corpus's index and records, FIRST — the shelf shelves the campaign first and every
# list view (adversaries, the Loremaster's folk, the Company) leads with the campaign's own.
# Replaces its own earlier copy, so a reload is a no-op.
INDEX = """(function(){var d=%s;var T=window.TOR2E=window.TOR2E||{books:{},entities:{},loaded:{}};
var I=T.index=T.index||{books:[],counts:{}};I.counts=I.counts||{};
var had=(I.books||[]).some(function(b){return b.id===d.book.id;});
I.books=(I.books||[]).filter(function(b){return b.id!==d.book.id;});I.books.unshift(d.book);
if(!had){I.counts.books=(I.counts.books||0)+1;I.counts.entities=(I.counts.entities||0)+d.book.counts.entities;
I.counts.files=(I.counts.files||0)+d.book.counts.chapters;var rc=I.counts.records=I.counts.records||{};
d.records.forEach(function(r){rc[r.type]=(rc[r.type]||0)+1;});}
T.records=d.records.concat((T.records||[]).filter(function(r){return r.book!==d.book.id;}));})();
"""


def layer_files(root):
    out = []
    for dirpath, _dirs, files in os.walk(root):
        for fn in files:
            if fn.endswith(DSL_EXTS + LORE_EXTS) and not fn.startswith("."):
                out.append(os.path.relpath(os.path.join(dirpath, fn), root))
    return sorted(out)


def corpus_index():
    src = open(os.path.join(HERE, "data", "index.js"), encoding="utf-8").read()
    m = INDEX_BLOB.search(src)
    if not m:
        raise SystemExit("build_layer: no data/index.js — run build/build.sh first")
    return json.loads(m.group(1))


def corpus_entities():
    """Every entity the built books carry (data/*.js): id → name, and every block id an arc
    declares (a SCENE, a LOCATION) — the targets a layer may point at."""
    ents, blocks = {}, set()
    data_dir = os.path.join(HERE, "data")
    for fn in sorted(os.listdir(data_dir)):
        if not fn.endswith(".js"):
            continue
        m = BLOB.search(open(os.path.join(data_dir, fn), encoding="utf-8").read())
        if not m:
            continue
        d = json.loads(m.group(1))
        for h, e in d["entities"].items():
            ents[h] = e.get("name")
        for c in d["book"]["chapters"]:
            for k in ("scenes", "locations", "entries"):
                blocks.update(b["id"] for b in c.get(k) or [] if b.get("id"))
    if not ents:
        raise SystemExit("build_layer: no book data in data/ — run build/build.sh first")
    return ents, blocks


def refs_in(node, hashed, named, where=""):
    """Every reference in the layer's data: {hash: …} / typeHash / ofHash / a Part's scene ids
    (hashed), and {hash: null, name: …} (named)."""
    if isinstance(node, dict):
        if "hash" in node and "name" in node and not node.get("hash") and isinstance(node.get("name"), str):
            named.append((where, node["name"]))
        for k, v in node.items():
            if k in ("hash", "typeHash", "ofHash") and isinstance(v, str):
                hashed.add(v)
            elif k == "scenes" and isinstance(v, list) and all(isinstance(x, str) for x in v):
                hashed.update(v)
            else:
                refs_in(v, hashed, named, node.get("name") if isinstance(node.get("name"), str) and k == "props" else where)
    elif isinstance(node, list):
        for x in node:
            refs_in(x, hashed, named, where)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("layer", help="the instance's DSL layer folder")
    ap.add_argument("--id", required=True, help="the layer's book id (e.g. campaign)")
    ap.add_argument("--label", required=True, help="the layer's title on the shelf")
    ap.add_argument("--out", required=True, help="where the two files go, relative to the site root")
    a = ap.parse_args()

    root = os.path.abspath(a.layer)
    rels = layer_files(root)
    if not rels:
        raise SystemExit("build_layer: no DSL or .lore files under %s" % a.layer)
    out_dir = os.path.abspath(a.out)
    os.makedirs(out_dir, exist_ok=True)
    book_path = os.path.join(out_dir, "%s.js" % a.id)
    src = os.path.relpath(book_path, HERE).replace(os.sep, "/")
    if src.startswith(".."):
        print("build_layer: note — %s lies outside the site, so no page can load it (fine for a test build)" % a.out)

    # ── build: one book, by build_data.py's own walk ─────────────────
    entities, order, chapters = {}, [], []
    for rel in rels:
        path = os.path.join(root, rel)
        ext = os.path.splitext(rel)[1]
        chapters.append(lore_chapter(path, rel) if ext in LORE_EXTS
                        else {"file": rel, "kind": ext[1:], "page": first_page(path, False), "_path": path})
    chapters.sort(key=lambda c: (EXT_ORDER.get(os.path.splitext(c["file"])[1], 9), c["file"]))
    roots = []
    for c in chapters:
        if c["kind"] == "lore":
            continue
        doc = parse_files([c.pop("_path")])[0]
        doc["file"] = c["file"]
        before = set(entities)
        c["roots"] = collect_entities(doc, a.id, entities)
        order.extend(h for h in entities if h not in before)
        c["container"] = doc["container"]
        c["cid"] = doc["name"]
        c["name"] = kwstr(doc["body"], "NAME")
        c.update(chapter_body(doc))
        roots.extend(c["roots"])

    types = set(corpus_index().get("types") or [])
    records = records_of(entities, order, types)
    rec = {"id": a.id, "label": a.label, "kind": KIND, "chapters": chapters, "entities": roots}
    with open(book_path, "w", encoding="utf-8") as fh:
        fh.write(BANNER)
        fh.write(REGISTER % json.dumps({"src": src, "book": rec, "entities": entities}, ensure_ascii=False, sort_keys=True))
    arcs = [c for c in chapters if c["kind"] == "arc"]
    index_rec = {
        "id": a.id, "label": a.label, "kind": KIND, "files": {"main": [src]},
        "chapters": [dict({"file": c["file"], "kind": c["kind"], "name": c.get("name"), "page": c["page"],
                           "cid": c.get("cid")}, **({"scenes": reading_order(c)} if c["kind"] == "arc" else {}))
                     for c in chapters],
        "counts": {"entities": len(entities), "chapters": len(chapters), "arcs": len(arcs),
                   "scenes": sum(len(c.get("scenes") or []) for c in chapters), "records": len(records)},
        "bytes": os.path.getsize(book_path),
    }
    with open(os.path.join(out_dir, "index.js"), "w", encoding="utf-8") as fh:
        fh.write(BANNER)
        fh.write(INDEX % json.dumps({"book": index_rec, "records": records}, ensure_ascii=False, sort_keys=True))
    print("build_layer: %d files → %s/%s.js (%d entities, %d records) and index.js"
          % (len(rels), a.out, a.id, len(entities), len(records)))

    # ── gates, read back from the files as written ───────────────────
    fail = 0
    want, skipped = strings_of(root, rels)
    book_blob = json.loads(LAYER_BLOB.search(open(book_path, encoding="utf-8").read()).group(1))
    index_blob = json.loads(LAYER_BLOB.search(open(os.path.join(out_dir, "index.js"), encoding="utf-8").read()).group(1))
    in_book = data_strings([book_blob])
    everywhere = in_book + data_strings([index_blob])
    ours = set(TYPE_WORDS) | KINDS | {KIND, a.label, src}
    missing = sorted(k for k in want if k not in in_book)
    short = sorted(k for k in want if k in in_book and in_book[k] < want[k])
    unsourced = sorted(k for k in everywhere if k not in want and k not in ours and k not in skipped)
    for label, rows in (("UNCOVERED — in the layer, not in its data", missing),
                        ("SHORT — printed more often than the data carries it", short),
                        ("UNSOURCED — in the data, not in the layer", unsourced)):
        if rows:
            fail = 1
            print("  %s: %d" % (label, len(rows)))
            for s in rows[:25]:
                print("    %r" % s[:130])
    if not (missing or short or unsourced):
        print("  strings: %d (%d occurrences) — 0 uncovered · 0 short · 0 unsourced" % (len(want), sum(want.values())))

    corpus, corpus_blocks = corpus_entities()
    taken = sorted(set(entities) & set(corpus))
    if taken:
        fail = 1
        print("  IDS — the layer reuses %d corpus ids: %s" % (len(taken), ", ".join(taken[:10])))
    else:
        print("  ids: %d, none of them the corpus's (%d)" % (len(entities), len(corpus)))

    hashed, named = set(), []
    refs_in(book_blob["entities"], hashed, named)
    refs_in(book_blob["book"]["chapters"], hashed, named)
    own_blocks = {b["id"] for c in chapters for k in ("scenes", "locations", "entries") for b in c.get(k) or [] if b.get("id")}
    dangling = sorted(hashed - set(entities) - set(corpus) - own_blocks - corpus_blocks)
    if dangling:
        fail = 1
        print("  REFERENCES — %d ids the layer points at are in neither the layer nor the corpus: %s"
              % (len(dangling), ", ".join(dangling[:10])))
    else:
        print("  references: %d ids, every one resolves (layer or corpus)" % len(hashed))
    by_name = {}
    for h, nm in corpus.items():
        by_name.setdefault(nm, []).append(h)
    for h, e in entities.items():
        by_name.setdefault(e["name"], []).append(h)
    unknown = [(w, nm) for w, nm in named if nm not in by_name]
    if unknown:
        fail = 1
        print("  NAMES — %d references name nothing in the layer or the corpus:" % len(unknown))
        for w, nm in unknown[:25]:
            print("    %r (in %s)" % (nm, w or "the layer"))
    else:
        print("  names: %d references by name, every one names an entity" % len(named))
    for w, nm in sorted(set(named)):
        if len(by_name.get(nm, [])) > 1:
            print("    note — %r (in %s) names %d entities" % (nm, w or "the layer", len(by_name[nm])))
    print("build_layer: %s" % ("FAILED" if fail else "OK"))
    return fail


if __name__ == "__main__":
    sys.exit(main())
